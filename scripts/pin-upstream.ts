// Record the exact commit and per-file hashes of the APE and RACE checkouts in vendor/ into src/upstream-manifest.ts.
// Run after updating a submodule: npm run pin:upstream
import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { sha256Hex, type UpstreamPin } from "../src/upstream.ts";

async function pin(dir: string, repo: string): Promise<UpstreamPin> {
  const commit = execFileSync("git", ["-C", dir, "rev-parse", "HEAD"]).toString().trim();
  const root = "prolog";
  const files: UpstreamPin["files"] = [];
  const walk = async (d: string) => {
    for (const e of fs.readdirSync(d, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
      const p = path.join(d, e.name);
      if (e.isDirectory()) await walk(p);
      else if (e.isFile() && !e.name.endsWith(".plp")) files.push({ path: path.relative(path.join(dir, root), p), sha256: await sha256Hex(new Uint8Array(fs.readFileSync(p))) });
    }
  };
  await walk(path.join(dir, root));
  return { repo, commit, root, files };
}

const manifest = { ape: await pin("vendor/APE", "Attempto/APE"), race: await pin("vendor/RACE", "Attempto/RACE") };
fs.writeFileSync(
  "src/upstream-manifest.ts",
  `// SPDX-License-Identifier: GPL-3.0-only\n` +
    `// Generated by scripts/pin-upstream.ts. Do not edit; run npm run pin:upstream after updating a submodule.\n` +
    `import type { UpstreamManifest } from "./upstream.ts";\n\n` +
    `export const UPSTREAM: UpstreamManifest = ${JSON.stringify(manifest, null, 2)};\n`,
);
console.log(`pinned APE ${manifest.ape.commit.slice(0, 7)} (${manifest.ape.files.length} files), RACE ${manifest.race.commit.slice(0, 7)} (${manifest.race.files.length} files)`);
